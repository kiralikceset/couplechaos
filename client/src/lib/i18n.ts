// Helper: Get random playful message by phase (localized)
export function getLocalizedPlayfulMessage(phase: string): string {
  const keys = Object.keys(translations[currentLocale]).filter(k => k.startsWith(`msg.${phase}`));
  if (keys.length === 0) return "";
  const randomKey = keys[Math.floor(Math.random() * keys.length)];
  return translations[currentLocale][randomKey] || "";
}

// Helper: Get random surprise message (localized)
export function getLocalizedSurpriseMessage(): string {
  const keys = Object.keys(translations[currentLocale]).filter(k => k.startsWith("msg.surprise"));
  if (keys.length === 0) return "";
  const randomKey = keys[Math.floor(Math.random() * keys.length)];
  return translations[currentLocale][randomKey] || "";
}


/**
 * Internationalization (i18n) System
 * Supports: Turkish (tr), English (en), German (de), Spanish (es)
 * Auto-detects device language and falls back to English
 */

export type Locale = "tr" | "en" | "de" | "es";

const LOCALE_KEY = "couple_chaos_locale";

// Detect device language from navigator
function detectLocale(): Locale {
  let stored: string | null = null;
  try {
    stored = typeof localStorage !== "undefined" ? localStorage.getItem(LOCALE_KEY) : null;
  } catch {
    stored = null;
  }
  if (stored && ["tr", "en", "de", "es"].includes(stored)) {
    return stored as Locale;
  }

  const browserLang = typeof navigator !== "undefined"
    ? navigator.language || (navigator as any).userLanguage || "en"
    : "en";
  const lang = browserLang.toLowerCase().split("-")[0];

  switch (lang) {
    case "tr": return "tr";
    case "de": return "de";
    case "es": return "es";
    default: return "en";
  }
}

let currentLocale: Locale = detectLocale();

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  currentLocale = locale;
  try {
    if (typeof localStorage !== "undefined") localStorage.setItem(LOCALE_KEY, locale);
  } catch {
    // Keep the selected locale for this session if storage is unavailable.
  }
}

// Translation function
export function t(key: string): string {
  const translation = translations[currentLocale]?.[key];
  if (translation) return translation;
  // Fallback to English
  return translations.en[key] || key;
}

